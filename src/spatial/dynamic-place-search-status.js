/**
 * Governed status model for AI MAP dynamic place search.
 * An empty legitimate search is not an execution failure.
 * A credential problem is not an AI failure.
 */

export const DYNAMIC_PLACE_ROUTE = 'DYNAMIC_PLACE_SEARCH';

export const DYNAMIC_PLACE_STATUS = Object.freeze({
  PASS: 'PASS',
  NO_VERIFIED_RESULTS: 'NO_VERIFIED_RESULTS',
  PROVIDER_UNAVAILABLE: 'PROVIDER_UNAVAILABLE',
  AUTH_REQUIRED: 'AUTH_REQUIRED',
  RATE_LIMITED: 'RATE_LIMITED',
  QUERY_NOT_UNDERSTOOD: 'QUERY_NOT_UNDERSTOOD',
  ANCHOR_NOT_RESOLVED: 'ANCHOR_NOT_RESOLVED',
  EXECUTION_FAILURE: 'EXECUTION_FAILURE'
});

export const DYNAMIC_PLACE_HTTP_STATUS = Object.freeze({
  [DYNAMIC_PLACE_STATUS.PASS]: 200,
  [DYNAMIC_PLACE_STATUS.NO_VERIFIED_RESULTS]: 200,
  [DYNAMIC_PLACE_STATUS.QUERY_NOT_UNDERSTOOD]: 400,
  [DYNAMIC_PLACE_STATUS.ANCHOR_NOT_RESOLVED]: 400,
  [DYNAMIC_PLACE_STATUS.AUTH_REQUIRED]: 401,
  [DYNAMIC_PLACE_STATUS.RATE_LIMITED]: 429,
  [DYNAMIC_PLACE_STATUS.PROVIDER_UNAVAILABLE]: 503,
  [DYNAMIC_PLACE_STATUS.EXECUTION_FAILURE]: 500
});

export function isSuccessfulPlaceStatus(status) {
  return status === DYNAMIC_PLACE_STATUS.PASS
    || status === DYNAMIC_PLACE_STATUS.NO_VERIFIED_RESULTS;
}

export function httpStatusForPlaceStatus(status, fallback = 400) {
  return DYNAMIC_PLACE_HTTP_STATUS[status] || fallback;
}
